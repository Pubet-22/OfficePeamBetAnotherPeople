-- ---------- users ----------
create table if not exists public.users (
    id             uuid primary key default gen_random_uuid(),
    email          text          not null unique,
    password       text          not null,   -- BCrypt hash
    full_name      text,
    role           text          not null default 'USER' check (role in ('USER', 'ADMIN')),
    is_premium     boolean       not null default false,
    premium_since  timestamptz,
    coin_balance   numeric(12, 2) not null default 0 check (coin_balance >= 0),
    created_at     timestamptz   not null default now(),
    updated_at     timestamptz   not null default now()
);

-- ---------- system_settings (มีแถวเดียว id = 1) ----------
create table if not exists public.system_settings (
    id                        smallint primary key default 1 check (id = 1),
    is_open                   boolean       not null default false,
    open_time                 time          not null default '10:00',
    close_time                time          not null default '16:00',
    timezone                  text          not null default 'Asia/Bangkok',
    rush_start                time          default '12:00',     -- ช่วงเร่งด่วน: สั่งได้เฉพาะ Premium
    rush_end                  time          default '13:00',
    coffee_service_fee        numeric(12, 2) not null default 20,  -- ค่าวิ่งไปเอากาแฟต่อออเดอร์ (ตัวเครื่องดื่มฟรี)
    general_service_fee       numeric(12, 2) not null default 20,  -- ค่าบริการงานจิปาถะต่อครั้ง
    premium_price             numeric(12, 2) not null default 199, -- ราคาอัปเกรด Premium (หักจาก wallet)
    premium_bonus_coins       numeric(12, 2) not null default 100, -- เหรียญแจกตอนเป็น Premium
    premium_discount_percent  numeric(5, 2)  not null default 10 check (premium_discount_percent between 0 and 100),
    qr_image_url              text,                                -- รูป QR Code จำลอง
    updated_at                timestamptz   not null default now()
);

-- ---------- coffee_menus ----------
create table if not exists public.coffee_menus (
    id            bigint generated by default as identity primary key,
    name          text          not null,
    description   text,
    price         numeric(12, 2) not null check (price >= 0),
    allow_hot     boolean       not null default true,
    allow_iced    boolean       not null default true,
    image_url     text,
    is_available  boolean       not null default true,
    sort_order    int           not null default 0,
    created_at    timestamptz   not null default now(),
    updated_at    timestamptz   not null default now()
);

-- ---------- topup_requests (คำขอเติมเงิน รอแอดมินตรวจสลิป) ----------
create table if not exists public.topup_requests (
    id             bigint generated by default as identity primary key,
    user_id        uuid          not null references public.users (id) on delete cascade,
    amount         numeric(12, 2) not null check (amount > 0),
    slip_url       text,
    status         text          not null default 'PENDING' check (status in ('PENDING', 'APPROVED', 'REJECTED')),
    reviewed_by    uuid references public.users (id),
    reviewed_at    timestamptz,
    reject_reason  text,
    created_at     timestamptz   not null default now()
);
create index if not exists idx_topup_user on public.topup_requests (user_id, created_at desc);
create index if not exists idx_topup_status on public.topup_requests (status, created_at);

-- ---------- orders ----------
create table if not exists public.orders (
    id                bigint generated by default as identity primary key,
    user_id           uuid          not null references public.users (id) on delete cascade,
    runner_id         uuid references public.users (id),
    service_type      text          not null check (service_type in ('COFFEE', 'GENERAL')),
    -- coffee
    menu_id           bigint references public.coffee_menus (id),
    quantity          int           not null default 1 check (quantity between 1 and 20),
    temperature       text check (temperature in ('HOT', 'ICED')),
    sweetness_level   int check (sweetness_level in (0, 25, 50, 75, 100)),
    -- general
    general_category  text check (general_category in ('WASH_GLASS', 'TRASH', 'PICKUP_FOOD', 'PRINT', 'OTHER')),
    custom_details    text,
    attachment_url    text,
    -- location
    desk_location     text          not null,
    location_note     text,
    -- lifecycle
    status            text          not null default 'PENDING'
                      check (status in ('PENDING', 'ACCEPTED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    is_priority       boolean       not null default false,
    cancel_reason     text,
    cancelled_by      uuid references public.users (id),
    accepted_at       timestamptz,
    started_at        timestamptz,
    completed_at      timestamptz,
    cancelled_at      timestamptz,
    -- money
    subtotal          numeric(12, 2) not null,
    discount_amount   numeric(12, 2) not null default 0,
    total_price       numeric(12, 2) not null,
    tip_amount        numeric(12, 2) not null default 0,
    payment_method    text          not null check (payment_method in ('WALLET', 'QR_MOCK')),
    payment_status    text          not null check (payment_status in ('PAID', 'AWAITING_VERIFICATION', 'REFUNDED', 'VOIDED')),
    payment_slip_url  text,
    created_at        timestamptz   not null default now(),
    updated_at        timestamptz   not null default now(),
    constraint coffee_needs_menu check (service_type <> 'COFFEE' or menu_id is not null),
    constraint general_needs_details check (service_type <> 'GENERAL' or custom_details is not null)
);
create index if not exists idx_orders_user on public.orders (user_id, created_at desc);
create index if not exists idx_orders_queue on public.orders (status, is_priority desc, created_at);

-- ---------- transactions (สมุดบัญชีเหรียญ) ----------
create table if not exists public.transactions (
    id             bigint generated by default as identity primary key,
    user_id        uuid          not null references public.users (id) on delete cascade,
    type           text          not null check (type in
                   ('TOPUP', 'ORDER_PAYMENT', 'REFUND', 'PREMIUM_UPGRADE', 'PREMIUM_BONUS', 'TIP_SENT', 'TIP_RECEIVED')),
    amount         numeric(12, 2) not null,  -- + เข้า / - ออก
    balance_after  numeric(12, 2) not null,
    order_id       bigint references public.orders (id),
    topup_id       bigint references public.topup_requests (id),
    note           text,
    created_at     timestamptz   not null default now()
);
create index if not exists idx_tx_user on public.transactions (user_id, created_at desc);

-- ---------- updated_at trigger ----------
create or replace function public.set_updated_at() returns trigger
language plpgsql as $$
begin
    new.updated_at = now();
    return new;
end $$;

drop trigger if exists trg_users_updated on public.users;
create trigger trg_users_updated before update on public.users
    for each row execute function public.set_updated_at();
drop trigger if exists trg_orders_updated on public.orders;
create trigger trg_orders_updated before update on public.orders
    for each row execute function public.set_updated_at();
drop trigger if exists trg_menus_updated on public.coffee_menus;
create trigger trg_menus_updated before update on public.coffee_menus
    for each row execute function public.set_updated_at();
drop trigger if exists trg_settings_updated on public.system_settings;
create trigger trg_settings_updated before update on public.system_settings
    for each row execute function public.set_updated_at();

-- ---------- ล้างของเก่าจากตอนใช้ Supabase Auth (ถ้ามี) ----------
drop trigger if exists on_auth_user_created on auth.users;
drop function if exists public.handle_new_user();
drop policy if exists users_select on public.users;
drop policy if exists settings_select on public.system_settings;
drop policy if exists menus_select on public.coffee_menus;
drop policy if exists topups_select on public.topup_requests;
drop policy if exists orders_select on public.orders;
drop policy if exists tx_select on public.transactions;
drop function if exists public.is_admin();

-- ---------- Row Level Security ----------
-- เปิด RLS แต่ไม่มี policy => anon key / Data API อ่านเขียนตารางไม่ได้เลย
-- ทุกอย่างต้องผ่าน backend (ที่ต่อด้วย role postgres ซึ่งข้าม RLS)
alter table public.users           enable row level security;
alter table public.system_settings enable row level security;
alter table public.coffee_menus    enable row level security;
alter table public.topup_requests  enable row level security;
alter table public.orders          enable row level security;
alter table public.transactions    enable row level security;

